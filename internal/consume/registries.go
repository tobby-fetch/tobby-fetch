package consume

import (
	"encoding/json"
	"sort"
	"strings"

	"github.com/tobby-fetch/tobby-fetch/internal/store"
)

// RegistriesYAML renders the K3s/RKE2 registries.yaml snippet of the
// selected recipes (FR-065 amendment).
//
// One mirror per nominal registry host of their ContainerImage
// ingredients. The mirror's endpoint is the destination; its rewrite rule
// is the one K3s and RKE2 document — a map of regular expressions matched
// against the image's repository name (host and tag excluded) to its
// replacement — mapping every repository of that host onto the relocated
// path (ADR-0013): "^(.*)$" → "<prefix>/<host>[_<port>]/$1". The tag or
// digest is not part of what a rewrite sees, so a digest-pinned reference
// keeps its digest.
//
// The document is plain text assembled here rather than marshalled: the
// header comment is part of the contract, key order is fixed, and every
// string goes through JSON quoting, a subset of YAML's double-quoted form.
// It never carries a credential (NFR-015): the only configs entry is the
// destination's CA file path, and the auth block is a commented placeholder.
func (s *Service) RegistriesYAML(sel []Selector) ([]byte, error) {
	if err := s.requireRegistry(); err != nil {
		return nil, err
	}
	records, err := s.selection(sel)
	if err != nil {
		return nil, err
	}
	rows, err := s.rows(records)
	if err != nil {
		return nil, err
	}

	type mirror struct{ prefix string }
	mirrors := map[string]mirror{}
	for i := range rows {
		if rows[i].Kind != string(store.KindContainerImage) {
			continue
		}
		host, path, _ := strings.Cut(rows[i].Nominal, "/")
		mirrors[host] = mirror{prefix: strings.TrimSuffix(rows[i].Relocated, "/"+path)}
	}
	hosts := make([]string, 0, len(mirrors))
	for h := range mirrors {
		hosts = append(hosts, h)
	}
	sort.Strings(hosts)

	scheme := "https"
	if s.set.Insecure {
		scheme = "http"
	}
	q := func(v string) string {
		b, _ := json.Marshal(v)
		return string(b)
	}

	var b strings.Builder
	b.WriteString("# registries.yaml for K3s and RKE2 — generated by Tobby " + s.set.Version + ".\n")
	b.WriteString("# Destination: " + s.set.Registry + " (" + scheme + ")\n")
	b.WriteString("# Recipes covered: ")
	if len(records) == 0 {
		b.WriteString("none")
	}
	for i := range records {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(records[i].Name + "@" + records[i].Version)
	}
	b.WriteString("\n#\n")
	b.WriteString("# Install it on every node as /etc/rancher/k3s/registries.yaml (K3s) or\n")
	b.WriteString("# /etc/rancher/rke2/registries.yaml (RKE2), then restart the k3s or rke2\n")
	b.WriteString("# service. Tobby never writes to a node.\n")
	b.WriteString("#\n")
	b.WriteString("# Limits. This redirects image pulls made by the node's container runtime and\n")
	b.WriteString("# nothing else. Helm chart sources, GitOps controllers, admission policies and\n")
	b.WriteString("# any tool that resolves image references itself must name the relocated\n")
	b.WriteString("# paths of the mapping table; Tobby never rewrites the values of a chart. A\n")
	b.WriteString("# digest-pinned reference keeps its digest through the rewrite.\n")
	b.WriteString("#\n")
	b.WriteString("# No credential is written here. If the destination requires one, fill the\n")
	b.WriteString("# auth placeholder below on the node.\n")

	if len(hosts) == 0 {
		b.WriteString("mirrors: {}\n")
	} else {
		b.WriteString("mirrors:\n")
	}
	for _, h := range hosts {
		prefix := mirrors[h].prefix
		b.WriteString("  " + q(h) + ":\n")
		b.WriteString("    endpoint:\n")
		b.WriteString("      - " + q(scheme+"://"+s.set.Registry) + "\n")
		b.WriteString("    rewrite:\n")
		b.WriteString("      " + q("^(.*)$") + ": " + q(prefix+"/$1") + "\n")
	}

	if s.set.CAFile != "" {
		b.WriteString("configs:\n")
		b.WriteString("  " + q(s.set.Registry) + ":\n")
		b.WriteString("    tls:\n")
		b.WriteString("      ca_file: " + q(s.set.CAFile) + "\n")
		b.WriteString("    # auth:\n    #   username: <fill on the node>\n    #   password: <fill on the node>\n")
	} else {
		b.WriteString("# configs:\n")
		b.WriteString("#   " + q(s.set.Registry) + ":\n")
		b.WriteString("#     auth:\n#       username: <fill on the node>\n#       password: <fill on the node>\n")
	}
	return []byte(b.String()), nil
}
