# Milestone-7 CROWN scenario (DEVELOPMENT-PLAN §2.7 exit criterion, moved
# from milestone 5 on 2026-08-26; arbitrage 6 of the milestone-7 opening):
# an RKE2 v1.36.5 cluster bootstrapped FULLY air-gapped from a bare OS, with
# everything served by Tobby. It exercises every milestone at once, so it is
# the last scenario written and the last one run.
#
#   1. Connected zone: a mirror instance synchronizes one signed recipe set —
#      the RKE2 v1.36.5 artifacts (binaries/tarballs, install material) and
#      the OS packages they need, as FileSets; the RKE2 system images and a
#      workload image, as ContainerImages — onto a real block device, with
#      the scanner and its database from the tobby-system channel. Pre-flight,
#      prune and the media manifest as in m5.
#   2. The device is detached and re-attached to the air-gapped side (canary
#      first). The destination instance verifies the medium, pushes it to the
#      zone registry, and serves the FileSets under /files/.
#   3. A BARE OS VM (Incus VM, its own kernel; no package mirror, no route
#      out) installs its OS packages from the FileSet served by Tobby (apt or
#      dnf repository, FR-047) and the RKE2 artifacts from /files/.
#   4. Its /etc/rancher/rke2/registries.yaml is the snippet GENERATED by
#      Tobby for the zone registry (FR-065) — written as produced, never
#      edited by the scenario.
#   5. RKE2 starts; every system pod becomes Ready pulling through the zone
#      registry by nominal references (registry access log as the witness);
#      a workload referencing docker.io/... runs.
#   6. The mapping table matches what the zone registry holds; no connection
#      left the air gap (canary and ACL counters).
#
# Topology:
#   tbc-m7z-source (container, tbc-net)     source registry + cookbook + channel
#   tbc-m7z-mirror (container, tbc-net)     mirror instance, writes the medium
#   tbc-m7z-dest   (container, tbc-airgap)  destination instance, /files/
#   tbc-m7z-zone   (container, tbc-airgap)  zone registry
#   tbc-m7z-rke2   (VM, tbc-airgap)         bare OS, the RKE2 server node
#                                           (profile with >= 4 CPU, 8 GiB)
#
# Run on its own (SCENARIO is set by crucible/run.sh when this is dispatched
# from m7/run.sh):  sh crucible/scenarios/m7/z-crown-rke2.sh
